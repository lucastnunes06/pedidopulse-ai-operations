"""Create browser screenshots using the real UI and deterministic backend fixtures.

This runs offline: HTML, CSS and JS come from app/static, and mocked HTTP responses
come from the actual Python service functions. No live server or third-party API.

Dependencies: pip install -r requirements-preview.txt; python -m playwright install chromium
"""
from __future__ import annotations

import asyncio
from io import BytesIO
import json
from pathlib import Path
import shutil

from PIL import Image
from playwright.async_api import async_playwright

from app.service import list_orders, metrics, triage

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
STATIC = ROOT / "app" / "static"


def build_preview_html():
    orders = list_orders()
    payload = {
        "orders": {"synthetic": True, "orders": orders},
        "metrics": metrics(),
        "triage": {
            order["order_id"]: triage(order["order_id"], "Fila alta no restaurante", "offline")
            for order in orders
        },
    }
    # Reuse the shipped frontend files; only replace network calls with fixtures
    # generated by the application's own Python functions.
    patch_fetch = """
    const fixture = window.__PEDIDOPULSE_DEMO__;
    window.fetch = async (url) => {
      const path = String(url);
      let data;
      if (path === '/api/orders') data = fixture.orders;
      else if (path === '/api/metrics') data = fixture.metrics;
      else if (path.startsWith('/api/triage/')) {
        data = fixture.triage[decodeURIComponent(path.split('/').pop())];
      }
      return new Response(JSON.stringify(data || { detail: 'Not found' }), {
        status: data ? 200 : 404,
        headers: { 'Content-Type': 'application/json' },
      });
    };
    """
    from bs4 import BeautifulSoup
    soup = BeautifulSoup((STATIC / "index.html").read_text(encoding="utf-8"), "html.parser")
    stylesheet = soup.find("link", href="/static/styles.css")
    assert stylesheet, "Stylesheet link missing"
    style = soup.new_tag("style")
    style.string = (STATIC / "styles.css").read_text(encoding="utf-8")
    stylesheet.replace_with(style)
    original = soup.find("script", src="/static/app.js")
    assert original, "Frontend script missing"
    script_tag = soup.new_tag("script")
    script_tag.string = ("window.__PEDIDOPULSE_DEMO__ = " + json.dumps(payload, ensure_ascii=False) + ";\n"
                         + patch_fetch + "\n" + (STATIC / "app.js").read_text(encoding="utf-8"))
    original.replace_with(script_tag)
    content = str(soup)
    assert "window.__PEDIDOPULSE_DEMO__" in content, "Front-end script not injected"
    return content


async def capture():
    html = build_preview_html()
    async with async_playwright() as playwright:
        path = shutil.which("chromium") or shutil.which("google-chrome")
        args = {"headless": True, "args": ["--no-sandbox"]}
        if path:
            args["executable_path"] = path
        browser = await playwright.chromium.launch(**args)
        page = await browser.new_page(viewport={"width": 1440, "height": 880}, device_scale_factor=1)
        errors = []
        page.on("pageerror", lambda exc: errors.append(str(exc)))
        await page.set_content(html, wait_until="load")
        await page.locator("#orders tr").first.wait_for()
        await page.locator("#result .evidence").first.wait_for()

        DOCS.mkdir(exist_ok=True)
        await page.screenshot(path=str(DOCS / "dashboard.png"), animations="disabled")
        first = Image.open(BytesIO(await page.screenshot(animations="disabled"))).convert("RGB")
        await page.locator("#filter").fill("PED-00019")
        await page.locator("#orders tr").first.click()
        await page.locator("#note").fill("Fila alta no restaurante")
        second = Image.open(BytesIO(await page.screenshot(animations="disabled"))).convert("RGB")
        await page.locator("#run").click()
        await page.locator("#result .evidence").first.wait_for()
        third = Image.open(BytesIO(await page.screenshot(animations="disabled"))).convert("RGB")
        assert not errors, f"JavaScript errors: {errors}"
        frames = [im.resize((960, 587)).quantize(colors=64, method=Image.Quantize.FASTOCTREE)
                  for im in (first, second, third)]
        frames[0].save(DOCS / "triage-demo.gif", save_all=True, append_images=frames[1:],
                       duration=[1400, 1300, 2600], loop=0, optimize=True)
        print(f"Rendered {await page.locator('#orders tr').count()} filtered row and 0 browser errors")
        await browser.close()


if __name__ == "__main__":
    asyncio.run(capture())
